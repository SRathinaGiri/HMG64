r"""Regenerate references/controls-syntax.md from HMG5's INCLUDE\*.ch.

Usage:  python skills/hmg/scripts/extract_syntax.py [path-to-HMG]   (default: two folders up)

Reads every "#xcommand" that defines a control or window (@ <row>,<col> <CONTROL> ...,
DEFINE WINDOW ..., DEFINE <CONTROL> for the alternate syntax) and writes its clauses as a
readable summary: [ OPTIONAL ] clauses, <placeholders>, alternatives with |.
The headers are the truth: when HMG changes, run this again instead of editing by hand.
"""
import os, re, sys

HMG = sys.argv[1] if len(sys.argv) > 1 else os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
INC = os.path.join(HMG, 'INCLUDE')
OUT = os.path.join(os.path.dirname(__file__), '..', 'references', 'controls-syntax.md')

# the files whose commands describe controls/windows, in a useful reading order
ORDER = ['i_window.ch', 'i_button.ch', 'i_label.ch', 'i_textbox.ch', 'i_editbox.ch', 'i_richeditbox.ch',
         'i_checkbox.ch', 'i_radiogroup.ch', 'i_combobox.ch', 'i_listbox.ch', 'i_grid.ch', 'i_browse.ch',
         'i_datepicker.ch', 'i_TimePicker.ch', 'i_monthcal.ch', 'i_spinner.ch', 'i_slider.ch',
         'i_progressbar.ch', 'i_tab.ch', 'i_tree.ch', 'i_frame.ch', 'i_image.ch', 'i_hyperlink.ch',
         'i_ipaddress.ch', 'i_timer.ch', 'i_menu.ch', 'i_status.ch', 'i_toolbar.ch', 'i_splitbox.ch',
         'i_media.ch', 'i_activex.ch', 'i_webview.ch', 'i_chart.ch']


def logical_commands(text):
    """join continuation lines (';' at the end) and yield (#xcommand head, body) pairs"""
    lines = text.replace('\r\n', '\n').split('\n')
    i = 0
    while i < len(lines):
        l = lines[i]
        if re.match(r'\s*#\s*xcommand\b', l, re.I):
            buf = [l]
            while buf[-1].rstrip().endswith(';') and i + 1 < len(lines):
                i += 1
                buf.append(lines[i])
            full = ' '.join(x.strip().rstrip(';').strip() for x in buf)
            yield full
        i += 1


def pretty(pattern):
    p = re.sub(r'\s+', ' ', pattern).strip()
    p = re.sub(r'^#\s*xcommand\s+', '', p, flags=re.I)
    # <name: A, B, C> (list marker): show the words as alternatives
    p = re.sub(r'<\s*\w+\s*:\s*([A-Za-z0-9_ ,.\\]+?)\s*>', lambda m: '|'.join(w.strip() for w in m.group(1).split(',')), p)
    p = p.replace('\\[', '[').replace('\\]', ']')
    return p


def clauses(pattern):
    """split '@ <row>,<col> BUTTON <name> [ OF <p> ] [ CAPTION <c> ] ...' into head + clause list"""
    p = pretty(pattern)
    out, depth, cur, head = [], 0, '', ''
    for ch in p:
        if ch == '[':
            if depth == 0:
                if not out and not head:
                    head = cur.strip()
                elif cur.strip():
                    out.append(cur.strip())
                cur = ''
            depth += 1
            cur += ch
        elif ch == ']':
            depth -= 1
            cur += ch
            if depth == 0:
                out.append(cur.strip())
                cur = ''
        else:
            cur += ch
    if cur.strip():
        if not head and not out:
            head = cur.strip()
        else:
            out.append(cur.strip())
    return head, out


def main():
    md = ['# HMG5 control and window syntax (generated)', '',
          'Generated by `scripts/extract_syntax.py` from HMG5\'s `INCLUDE\\*.ch` - the clauses each command',
          'really accepts. `[ ... ]` = optional, `A|B` = one of, `<x>` = your value/expression,',
          '`<{x}>`-type clauses (ON ..., ACTION) take an expression or a codeblock. Clause order is free.',
          'Where a control has several command forms (e.g. GRID with/without ROWSOURCE), all are listed.', '']
    seen = set()
    for fn in ORDER:
        path = os.path.join(INC, fn)
        if not os.path.exists(path):
            continue
        text = open(path, 'rb').read().decode('latin-1')
        cmds = []
        for full in logical_commands(text):
            pat = full.split('=>')[0]
            if not re.search(r'#\s*xcommand\s+(@\s*<|DEFINE\s+WINDOW|DEFINE\s+\w+\s+<)', pat, re.I):
                continue
            if re.search(r'DEFINE\s+(MAIN\s+MENU|POPUP|CONTEXT|NODE|PAGE|STATUSBAR|TOOLBAR|SPLITBOX)', pat, re.I) is None and \
               re.search(r'DEFINE\s+\w+\s+<', pat, re.I) and fn != 'i_window.ch' and not re.search(r'@\s*<', pat):
                # alternate syntax 'DEFINE X <name>' (clauses on following lines): name it, no clauses
                pass
            head, cl = clauses(pat)
            key = (head, tuple(cl))
            if key in seen:
                continue
            seen.add(key)
            cmds.append((head, cl))
        if not cmds:
            continue
        md.append('## ' + fn[:-3].replace('i_', '').upper())
        md.append('')
        for head, cl in cmds:
            md.append('```')
            md.append(head)
            for c in cl:
                md.append('    ' + c)
            md.append('```')
        md.append('')
    # a table of contents after the introduction (the file is long)
    heads = [l[3:] for l in md if l.startswith('## ')]
    toc = ['Contents: ' + ', '.join('[%s](#%s)' % (h, h.lower()) for h in heads), '']
    md = md[:7] + toc + md[7:]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(md))
    print('wrote', os.path.normpath(OUT), sum(1 for l in md if l == '```') // 2, 'commands')


if __name__ == '__main__':
    main()
