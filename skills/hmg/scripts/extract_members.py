"""Regenerate references/properties-methods.md from the HMG5 IDE's member table.

Usage:  python skills/hmg/scripts/extract_members.py [path-to-HMG]

The table lives in SOURCE/IDE_SourceCode/Source/ide_complete.prg (IDE_MemberTable). The IDE's
self-test checks that every name in it is one that GetProperty / SetProperty / DoMethod
(SOURCE/h_controlmisc.prg, h_webview.prg, h_chart.prg) understand, so this list is real.
"""
import os, re, sys

HMG = sys.argv[1] if len(sys.argv) > 1 else os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
SRC = os.path.join(HMG, 'SOURCE', 'IDE_SourceCode', 'Source', 'ide_complete.prg')
OUT = os.path.join(os.path.dirname(__file__), '..', 'references', 'properties-methods.md')

text = open(SRC, 'rb').read().decode('latin-1').replace('\r\n', '\n')
body = text[text.index('s_a := {'):text.index('RETURN s_a')]
# join Harbour continuations: '" + ;\n   "' -> ''
body = re.sub(r'"\s*\+\s*;\s*\n\s*"', '', body)
rows = re.findall(r'\{\s*"([A-Z*]+)"\s*,\s*"([^"]*)"\s*,\s*;?\s*"([^"]*)"\s*,\s*(\.[TF]\.)\s*\}', body)

md = ['# HMG5 properties and methods by control type (generated)', '',
      'Generated by `scripts/extract_members.py` from the HMG5 IDE\'s completion table, which the IDE\'s',
      'self-test checks against GetProperty / SetProperty / DoMethod in the library source.', '',
      'Use them as `Form.Control.Property` (get), `Form.Control.Property := x` (set) and',
      '`Form.Control.Method` or `Form.Control.Method( args )`; for a window `Form.Property` / `Form.Method`.',
      'The same names work with `GetProperty( "Form", "Control", "Prop" )`, `SetProperty( "Form", "Control",',
      '"Prop", x )` and `DoMethod( "Form", "Control", "Method" [, args] )` - the function form also works',
      'with names held in variables and from modules where the window is not DECLAREd.', '',
      'Rows marked "+ common" also have every property/method of the `*` row.', '']
for typ, props, meths, common in rows:
    title = {'*': 'Common to every visible control', 'WINDOW': 'WINDOW (forms)'}.get(typ, typ)
    md.append('## ' + title + ('' if typ in ('*', 'WINDOW') or common == '.F.' else '  (+ common)'))
    md.append('')
    if props.strip():
        md.append('- **Properties:** ' + ', '.join(props.split()))
    if meths.strip():
        md.append('- **Methods:** ' + ', '.join(meths.split()))
    md.append('')
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(md))
print('wrote', os.path.normpath(OUT), len(rows), 'types')
